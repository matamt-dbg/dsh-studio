import { createHash, randomBytes } from 'node:crypto';
import { chmod, mkdir, rename, writeFile } from 'node:fs/promises';
import type { IncomingMessage, ServerResponse } from 'node:http';
import { join } from 'node:path';
import type { JudgeAnswer, JudgeQuestion } from '../pixie-contracts.ts';
import { validateJudgeRequest } from '../pixie-contracts.ts';

/** Prefix route on the DSH `webServer`; `/ask` and `/judge` below it. */
export const HELPER_ROUTE = '/studio/pixie-gate/helper';
export const HELPER_LIMITS = { calls: 20, bodyBytes: 256 * 1024 } as const;

/** What one hook script run may ask; nothing else is reachable with its token. */
export interface HelperGrant {
  /** Default helper input: the gate target, used when `--input` is not given. */
  target: string;
  /** The gate run's signal (cancellation and timeout). */
  signal: AbortSignal;
  ask(instruction: string, input: string, signal: AbortSignal): Promise<string>;
  judge(request: HelperJudgeRequest, input: string, signal: AbortSignal): Promise<HelperJudgement>;
}
/** Helper-facing question kinds; `bool` is Jev's noul, `select` its choice. */
export type HelperJudgeType = 'bool' | 'select' | 'score';
export interface HelperJudgeRequest { type: HelperJudgeType; question: JudgeQuestion; threshold: number }
/** One `pixie judge` outcome: the exit code and plain stdout the script sees, and the `--json` line. */
export interface HelperJudgement {
  exit: 0 | 1; text: string;
  json: { type: HelperJudgeType; label: string; answer: JudgeAnswer; threshold?: number; engine?: string; model?: string };
}

/** Label rule shared by the route and the run record: bool by threshold, select by choice, score by the nearest level. */
export function helperJudgement(request: HelperJudgeRequest, answer: JudgeAnswer, meta: { engine?: string; model?: string } = {}): HelperJudgement {
  const extra = { ...(meta.engine ? { engine: meta.engine } : {}), ...(meta.model ? { model: meta.model } : {}) };
  if (answer.type === 'noul') {
    const pass = answer.noul >= request.threshold;
    return { exit: pass ? 0 : 1, text: String(answer.noul), json: { type: 'bool', label: pass ? 'yes' : 'no', answer, threshold: request.threshold, ...extra } };
  }
  if (answer.type === 'choice') return { exit: 0, text: answer.choice, json: { type: 'select', label: answer.choice, answer, ...extra } };
  return { exit: 0, text: String(answer.score), json: { type: 'score', label: String(Math.round(answer.score)), answer, ...extra } };
}

/** Build and validate the question a helper request asks; throws a usage error naming the problem. */
export function helperJudgeRequest(form: URLSearchParams): HelperJudgeRequest {
  const type = (form.get('type') ?? 'bool') as HelperJudgeType;
  if (!['bool', 'select', 'score'].includes(type)) throw new Error('type must be bool, select, or score');
  const instructions = form.get('question')?.trim();
  if (!instructions) throw new Error('question is required');
  const raw = form.get('threshold'), threshold = raw === null ? 0.5 : Number(raw);
  if (!(threshold >= 0 && threshold <= 1)) throw new Error('threshold must be between 0 and 1');
  let question: JudgeQuestion;
  if (type === 'bool') {
    const yes = form.get('true'), no = form.get('false');
    question = { type: 'noul', instructions, ...(yes !== null || no !== null ? { criteria: { ...(yes !== null ? { true: yes } : {}), ...(no !== null ? { false: no } : {}) } } : {}) };
  } else if (type === 'select') {
    const criteria: Record<string, string> = {};
    for (const option of form.getAll('option')) {
      const at = option.indexOf('=');
      const name = (at < 0 ? option : option.slice(0, at)).trim();
      if (!name || Object.hasOwn(criteria, name)) throw new Error(`option names must be unique and non-empty: ${option}`);
      criteria[name] = at < 0 ? name : option.slice(at + 1);
    }
    question = { type: 'choice', instructions, criteria };
  } else question = { type: 'score', instructions, criteria: form.getAll('level') };
  validateJudgeRequest({ state: '', questions: { helper: question } });
  return { type, question, threshold };
}

export interface HelperSession { env: Record<string, string>; revoke(): void }
interface Grant { grant: HelperGrant; calls: number; revoked: AbortController }

/** The `pixie` command placed first on the script's PATH. Uses curl; writes no files (read-only sandboxes). */
export const HELPER_SCRIPT = `#!/usr/bin/env bash
# Pixie Gate hook helper, generated by DSH Studio. Valid only inside one hook script run.
#   pixie ask "<instruction>" [--input]
#   pixie judge [--type bool|select|score] --question "<question>" [--threshold 0.5] [--true ..] [--false ..]
#               [--option name=desc ..] [--level desc ..] [--json] [--input]
# --input reads the helper input from stdin; otherwise the gate target is used.
set -u
fail() { printf 'pixie: %s\\n' "$1" >&2; exit 2; }
[ -n "\${PIXIE_URL:-}" ] && [ -n "\${PIXIE_TOKEN:-}" ] || fail 'helper is not available outside a Pixie Gate hook script run'
command -v curl >/dev/null 2>&1 || fail 'curl is required'
command="\${1:-}"; [ $# -gt 0 ] && shift
input=0; args=()
case "$command" in
  ask)
    [ $# -ge 1 ] || fail 'usage: pixie ask "<instruction>" [--input]'
    args+=(--data-urlencode "instruction=$1"); shift
    while [ $# -gt 0 ]; do case "$1" in --input) input=1 ;; *) fail "unknown option: $1" ;; esac; shift; done ;;
  judge)
    question=''; json=0
    while [ $# -gt 0 ]; do case "$1" in
      --type|--question|--threshold|--true|--false|--option|--level)
        [ $# -ge 2 ] || fail "$1 needs a value"
        [ "$1" = --question ] && question="$2"
        args+=(--data-urlencode "\${1#--}=$2"); shift ;;
      --json) json=1 ;;
      --input) input=1 ;;
      *) fail "unknown option: $1" ;;
    esac; shift; done
    [ -n "$question" ] || fail 'usage: pixie judge [--type bool|select|score] --question "<question>" [--threshold 0.5] [--true ..] [--false ..] [--option name=desc ..] [--level desc ..] [--json] [--input]' ;;
  *) fail 'usage: pixie ask|judge ...' ;;
esac
[ "$input" = 1 ] && args+=(--data-urlencode 'input@-')
# The token travels in a config on a file descriptor, never on the command line.
out=$(curl -sS --noproxy '*' -X POST -K <(printf 'header = "Authorization: Bearer %s"\\n' "$PIXIE_TOKEN") -w '\\n%{http_code}' "\${args[@]}" "$PIXIE_URL/$command") || fail "request failed"
code=\${out##*$'\\n'}; body=\${out%$'\\n'*}
[ "$code" = 200 ] || fail "HTTP $code: $body"
if [ "$command" = ask ]; then printf '%s\\n' "$body"; exit 0; fi
# judge body: exit code, plain answer, then the JSON line.
status=\${body%%$'\\n'*}; rest=\${body#*$'\\n'}; text=\${rest%%$'\\n'*}; line=\${rest#*$'\\n'}
if [ "$json" = 1 ]; then printf '%s\\n' "$line"; else printf '%s\\n' "$text"; fi
exit "$status"
`;

const hash = (token: string) => createHash('sha256').update(token).digest('hex');
const send = (res: ServerResponse, status: number, text: string) => {
  if (res.headersSent) return;
  res.writeHead(status, { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' });
  res.end(text);
};

/** Per-run tokens for `pixie ask/judge` (U23). Tokens are issued for one script run and revoked when it ends. */
export class PixieGateHelper {
  private grants = new Map<string, Grant>();
  private installed: Promise<void> | undefined;
  private readonly limits: { calls: number; bodyBytes: number };
  constructor(private readonly options: { binDirectory: string; url(): string | undefined; limits?: { calls: number; bodyBytes: number } }) {
    this.limits = options.limits ?? HELPER_LIMITS;
  }

  /** Environment for one script run. Without a reachable route only PATH is given and `pixie` explains why. */
  async issue(grant: HelperGrant): Promise<HelperSession> {
    await (this.installed ??= this.install().catch(error => { this.installed = undefined; throw error; }));
    const env: Record<string, string> = { PATH: `${this.options.binDirectory}:${process.env.PATH ?? '/usr/bin:/bin'}` };
    const url = this.options.url();
    if (!url) return { env, revoke() {} };
    const token = randomBytes(32).toString('hex'), key = hash(token);
    const entry: Grant = { grant, calls: 0, revoked: new AbortController() };
    this.grants.set(key, entry);
    return { env: { ...env, PIXIE_URL: url, PIXIE_TOKEN: token }, revoke: () => { this.grants.delete(key); entry.revoked.abort(new Error('Pixie helper token revoked')); } };
  }

  readonly handle = async (req: IncomingMessage, res: ServerResponse): Promise<void> => {
    const action = new URL(req.url ?? '/', 'http://x').pathname.slice(HELPER_ROUTE.length);
    if (action !== '/ask' && action !== '/judge') return send(res, 404, 'unknown helper');
    if (req.method !== 'POST') return send(res, 405, 'POST only');
    const header = req.headers.authorization;
    const entry = typeof header === 'string' && header.startsWith('Bearer ') ? this.grants.get(hash(header.slice(7))) : undefined;
    if (!entry) return send(res, 401, 'invalid or expired token');
    if (entry.calls >= this.limits.calls) return send(res, 429, `helper call limit (${this.limits.calls}) reached`);
    const body = await this.read(req);
    if (body === undefined) return send(res, 413, `helper request exceeds ${this.limits.bodyBytes} bytes`);
    if (!this.grants.has(hash(header!.slice(7)))) return send(res, 401, 'invalid or expired token');
    const form = new URLSearchParams(body);
    const input = form.get('input') ?? entry.grant.target;
    const closed = new AbortController();
    res.on('close', () => { if (!res.writableFinished) closed.abort(new Error('Helper client disconnected')); });
    const signal = AbortSignal.any([entry.grant.signal, entry.revoked.signal, closed.signal]);
    let call: Promise<string>;
    if (action === '/ask') {
      const instruction = form.get('instruction')?.trim();
      if (!instruction) return send(res, 400, 'instruction is required');
      entry.calls++;
      call = entry.grant.ask(instruction, input, signal);
    } else {
      let request: HelperJudgeRequest;
      try { request = helperJudgeRequest(form); } catch (error) { return send(res, 400, error instanceof Error ? error.message : String(error)); }
      entry.calls++;
      call = entry.grant.judge(request, input, signal).then(result => `${result.exit}\n${result.text.replace(/\n/g, ' ')}\n${JSON.stringify(result.json)}`);
    }
    try { send(res, 200, await call); }
    catch (error) { send(res, signal.aborted ? 503 : 502, error instanceof Error ? error.message : String(error)); }
  };

  /** Body text, or undefined above the size limit (the rest is drained, then the socket closed past 4×). */
  private read(req: IncomingMessage): Promise<string | undefined> {
    return new Promise((resolve, reject) => {
      const chunks: Buffer[] = []; let size = 0;
      req.on('data', (chunk: Buffer) => {
        size += chunk.length;
        if (size <= this.limits.bodyBytes) chunks.push(chunk);
        else if (size > this.limits.bodyBytes * 4) { req.destroy(); resolve(undefined); }
      });
      req.on('end', () => resolve(size > this.limits.bodyBytes ? undefined : Buffer.concat(chunks).toString('utf8')));
      req.on('error', reject);
    });
  }

  private async install() {
    await mkdir(this.options.binDirectory, { recursive: true });
    const path = join(this.options.binDirectory, 'pixie'), temp = `${path}.${process.pid}.tmp`;
    await writeFile(temp, HELPER_SCRIPT, { mode: 0o755 });
    await chmod(temp, 0o755);
    await rename(temp, path);
  }
}
